import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import { unzipSync } from 'fflate';
test('multi-play ALL controls export image/video ZIPs and multipage PDF', async ({ page }) => {
	await page.goto('/diagram/flag-football');
	await page.waitForSelector('.tutorial-launch-bouncing');
	const consent = page.getByRole('button', { name: /^Essential Cookies Only/ });
	if (await consent.isVisible()) await consent.click();
	await page.getByRole('button', { name: 'More image formats', exact: true }).click();
	await expect(page.getByRole('button', { name: /Export All Plays as/ })).toHaveCount(0);
	await page.keyboard.press('Escape');
	await page.getByRole('button', { name: 'Add another play', exact: true }).click();
	await page.getByRole('button', { name: 'More image formats', exact: true }).click();
	let pending = page.waitForEvent('download');
	await page.getByRole('button', { name: 'Export All Plays as PNG', exact: true }).click();
	let file = await pending;
	expect(Object.keys(unzipSync(await readFile((await file.path())!)))).toHaveLength(2);
	await page.getByRole('button', { name: 'More image formats', exact: true }).click();
	pending = page.waitForEvent('download');
	await page.getByRole('button', { name: 'Export All Plays as PDF', exact: true }).click();
	file = await pending;
	expect((await readFile((await file.path())!)).toString()).toContain('/Count 2');
	await page.getByRole('button', { name: 'More image formats', exact: true }).click();
	pending = page.waitForEvent('download');
	await page.getByRole('button', { name: 'Export PDF image', exact: true }).click();
	file = await pending;
	expect((await readFile((await file.path())!)).toString()).toContain('/Count 1');
	await page.getByRole('button', { name: 'Animate play', exact: true }).click();
	await page.getByRole('button', { name: 'Add animation step', exact: true }).click();
	const duration = page.getByRole('spinbutton', { name: 'Step duration seconds', exact: true });
	await duration.fill('0.1');
	await duration.press('Enter');
 await page.getByRole('button',{name:'More video formats',exact:true}).click();
 await expect(page.getByRole('button',{name:/Export All Plays as/})).toHaveCount(0);
 await page.keyboard.press('Escape');await page.keyboard.press('Alt+a');
 await page.locator('[data-play-id]').first().click();
 await expect(page.getByRole('button',{name:'Export MP4 video',exact:true})).toBeEnabled();
 pending=page.waitForEvent('download');await page.getByRole('button',{name:'Export MP4 video',exact:true}).click();
 file=await pending;expect(file.suggestedFilename()).toBe('Play 2 Animation.mp4');
 await page.getByRole('button',{name:'Animate play',exact:true}).click();
 await page.getByRole('button',{name:'Add animation step',exact:true}).click();
 await duration.fill('0.1');await duration.press('Enter');
 await page.keyboard.press('Alt+a');
 await page.getByRole('button',{name:'Add another play',exact:true}).click();
	await page.getByRole('button', { name: 'More video formats', exact: true }).click();
	pending = page.waitForEvent('download');
	await page.getByRole('button', { name: 'Export All Plays as MP4', exact: true }).click();
	file = await pending;
	const files = unzipSync(await readFile((await file.path())!));
	expect(Object.keys(files)).toHaveLength(2);
	for (const bytes of Object.values(files)) expect(Buffer.from(bytes).toString('ascii', 4, 8)).toBe('ftyp');
 await expect(page.locator('[data-play-id][aria-pressed="true"]')).toHaveText('Play 3');
});
