import { test, expect } from '@playwright/test';
test('player letters affect only the current play and become defaults for new plays', async ({ page }) => {
	await page.goto('/diagram/flag-football');
	await page.waitForSelector('.tutorial-launch-bouncing');
	const consent = page.getByRole('button', { name: /^Essential Cookies Only/ });
	if (await consent.isVisible()) await consent.click();
	await page.getByRole('button', { name: 'Set up default play', exact: true }).click();
	await page.getByRole('button', { name: 'Add another play', exact: true }).click();
	await page.getByRole('button', { name: 'Set up default play', exact: true }).click();
	await page.getByRole('button', { name: 'Animate play', exact: true }).click();
	await page.getByRole('button', { name: 'Add animation step', exact: true }).click();
	await page.getByRole('button', { name: 'Team A', exact: true }).click({ button: 'right' });
	const input = page.getByRole('textbox', { name: 'Player letter', exact: true });
	await expect(input).toHaveValue('A');
	await input.fill('x');
	await input.press('Enter');
	await expect(page.getByRole('button', { name: 'Team X', exact: true })).toHaveText('X');
	await expect(page.locator('[data-layer-type="marker"][data-field-kind="team-a"]')).toContainText('X-1');
	await page.keyboard.press('Escape');
	await page.keyboard.press('Control+z');
	await expect(page.getByRole('button', { name: 'Team A', exact: true })).toHaveText('A');
	await page.keyboard.press('Control+Shift+z');
	await expect(page.getByRole('button', { name: 'Team X', exact: true })).toHaveText('X');
	await page.keyboard.press('1');
	await expect(page.locator('[data-layer-type="marker"][data-field-kind="team-a"]')).toContainText('X-1');
	await page.keyboard.press('Alt+a');
	await page.getByRole('button', { name: 'Open Play 1', exact: true }).click();
	await expect(page.getByRole('button', { name: 'Team A', exact: true })).toHaveText('A');
	await expect(page.locator('[data-layer-type="marker"][data-field-kind="team-a"]')).toContainText('A-1');
	await page.getByRole('button', { name: 'Add another play', exact: true }).click();
	await expect(page.getByRole('button', { name: 'Team X', exact: true })).toHaveText('X');
	await page.getByRole('button', { name: 'Set up default play', exact: true }).click();
	await expect(page.locator('[data-layer-type="marker"][data-field-kind="team-a"]')).toContainText('X-1');
	expect(await page.evaluate(() => JSON.parse(localStorage.getItem('caseplay-play-builder-tool-preferences-v1')!).playerLetters)).toBe('XBKR');
	const response = page.waitForResponse((r) => r.url().endsWith('/api/play-builders') && r.request().method() === 'POST');
	await page.getByRole('button', { name: 'Save play', exact: true }).click();
	const saved = await response;
	expect(saved.status()).toBe(201);
	const document = await saved.json();
	await page.waitForURL((url) => url.pathname === `/diagram/flag-football/${document.id}`);
	await page.reload();
	await page.waitForLoadState('networkidle');
	await expect(page.getByRole('button', { name: 'Team X', exact: true })).toHaveText('X');
	await page.getByRole('button', { name: 'Open Play 1', exact: true }).click();
	await expect(page.getByRole('button', { name: 'Team A', exact: true })).toHaveText('A');
	await page.getByRole('button', { name: 'Open Play 2', exact: true }).click();
	await expect(page.getByRole('button', { name: 'Team X', exact: true })).toHaveText('X');

	const fresh = await page.context().newPage();
	await fresh.goto('/diagram/flag-football');
	await fresh.waitForLoadState('networkidle');
	await expect(fresh.getByRole('button', { name: 'Team X', exact: true })).toHaveText('X');
	await expect(fresh.getByRole('button', { name: 'Save play', exact: true })).toBeDisabled();
	await fresh.close();
});
